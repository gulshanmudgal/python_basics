# Arithmetic Operators
# addition       = 3 + 2 
# subtraction    = 3 - 2
# multiplication = 3 * 2
# division       = 3 / 2 = 1.5
# floor division = 3 // 2 = 1
# modulus        = 3 % 2 = 1
# exponentiation = 3 ** 2 = 9

num = 2
num += 3 # num = num + 3

num *= 6 # num = num * 6
print(num)

# In-built functions
abs(-3) # 3
round(3.75) # 4
round(3.75, 1) # 3.8

# Comparisons
# Equal                    : ==; 3 == 2
# Not Equal                : !=; 3 != 2
# Greater Than             : >;  3 > 2
# Less Than                : <; 3 < 2
# Greater Than or Equal To : >=; 3 >= 2 
# Less Than or Equal To    : <=; 3 <= 2

# Casting
int(3.75) # 3
float(8) # 8.0

num1 = '100'
num2 = '200'

print(num1 + num2)

num1 = int(num1)
num2 = int(num2)

print(num1 + num2)
